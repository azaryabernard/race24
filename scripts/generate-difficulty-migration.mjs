/** Regenerate migration 004 from the exact v2 engine. Run: node scripts/generate-difficulty-migration.mjs */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { analyzeHand, RULES_VERSION, DIFFICULTY_VERSION } from '../shared/engine.js';

if (RULES_VERSION !== 1 || DIFFICULTY_VERSION !== 2)
  throw Error('Review the migration version when changing the rules or classifier');
const rows = [];
const distribution = {};
for (let a = 1; a <= 10; a++) for (let b = a; b <= 10; b++)
  for (let c = b; c <= 10; c++) for (let d = c; d <= 10; d++) {
    const report = analyzeHand([a, b, c, d].map(n => n === 1 ? 'A' : String(n)));
    distribution[report.difficulty] = (distribution[report.difficulty] || 0) + 1;
    if (report.solvable) rows.push(`  ('${report.key}', '${report.difficulty}', ${report.score})`);
  }
const out = `-- Race24 difficulty v2. GENERATED by scripts/generate-difficulty-migration.mjs.
-- Apply after 001, 002, and 003, after taking a database backup.
-- Reclassifies all 617 solvable canonical four-value hands (A=1 or 11;
-- 10/J/Q/K=10) under the EXISTING rules_version=1. Does not delete records,
-- replace players/families, change best times, or reset scoreboards.
-- Safe to rerun: same values and guarded UPDATEs, no schema changes.
-- Deploy the matching updated Supabase 'solo' Edge Function after applying.
begin;
create temporary table race24_difficulty_v2 (
  hand_key text primary key,
  difficulty text not null,
  score integer not null
) on commit drop;
insert into race24_difficulty_v2 (hand_key, difficulty, score) values
${rows.join(',\n')};

update public.hands as h set
  difficulty = d.difficulty, score = d.score
from race24_difficulty_v2 as d
where h.rules_version = 1 and h.hand_key = d.hand_key
  and (h.difficulty, h.score) is distinct from (d.difficulty, d.score);

-- Reconcile verified bests with their canonical hand entry while leaving times,
-- player IDs, family IDs, and updated_at fields exactly as they were.
update public.player_hand_bests as b set difficulty = h.difficulty
from public.hands as h
where b.rules_version = 1 and h.rules_version = b.rules_version
  and b.hand_key = h.hand_key and b.difficulty is distinct from h.difficulty;

update public.family_hand_bests as b set difficulty = h.difficulty
from public.hands as h
where b.rules_version = 1 and h.rules_version = b.rules_version
  and b.hand_key = h.hand_key and b.difficulty is distinct from h.difficulty;
commit;
`;
const destination = resolve(dirname(fileURLToPath(import.meta.url)), '../supabase/migrations/004_difficulty_v2.sql');
writeFileSync(destination, out);
console.log(`Wrote ${rows.length} mappings to ${destination}. Difficulty distribution: ${JSON.stringify(distribution)}`);
